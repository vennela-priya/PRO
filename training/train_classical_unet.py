"""
training/train_classical_unet.py
==================================
Trains Attention U-Net on classical pseudo-masks generated by
    refinement/classical_mask_generator.py --dataset

Run (CPU — ~50 min for 50 epochs on 5712 images):
    python training/train_classical_unet.py

Run with custom settings:
    python training/train_classical_unet.py --epochs 30 --batch_size 4

For GPU (Colab/Kaggle) add:
    python training/train_classical_unet.py --batch_size 16 --epochs 50

Prerequisite:
    python refinement/classical_mask_generator.py --dataset
    (generates outputs/classical_masks/ — run once)

Output:
    checkpoints/unet/best_unet.pth          <- used by pipeline.py
    checkpoints/unet/curves.png             <- training curves
    checkpoints/unet/vis/ep*.png            <- sample predictions per epoch
    unet_train.log                          <- full training log
"""
